-- Несколько актуальных графиков на одном объекте.
--
-- addresses.schedule_type — одно значение: в выгрузке «Лавки» на одном
-- адресе встречаются тикеты с разными графиками («2/2» у одной должности,
-- «5/2» у другой), и до сих пор импорт брал первый распознанный, а
-- остальные молча терял (известное ограничение в
-- docs/requirements/addresses.md). Отдельная колонка-список вместо
-- расширения старой: schedule_type остаётся тем, что координатор ведёт
-- руками (одно значение, селект в карточке), schedule_types — тем, что
-- импорт пересчитывает из текущей выгрузки.
--
-- Пересчитывается, а не копится: список отражает графики, реально видные в
-- последнем импорте по этому адресу — как required_count отражает текущую
-- потребность, а не её историю. Исключение — импорт, не нашедший для
-- объекта ни одного графика (в файле нет колонки «График» или ячейки
-- пустые): он список не трогает, иначе выгрузка без условий стирала бы уже
-- собранные данные.

-- `if not exists` — миграции применяются руками через SQL Editor, без
-- раннера, отслеживающего «применено/нет»: повторный запуск не должен
-- падать с `42701`.
alter table public.addresses
  add column if not exists schedule_types text[] not null default '{}';

comment on column public.addresses.schedule_types is
  'Актуальные графики объекта, собранные импортом из всех тикетов этого адреса (src/lib/imports/addressPlan.ts). Пересчитывается каждым импортом, нашедшим хотя бы один график; пустой массив = импорт графиков не приносил. Ручное поле координатора — schedule_type (одно значение), импорт его не перезаписывает.';

-- Те же семь значений, что у CHECK на schedule_type: `<@` требует, чтобы
-- каждый элемент массива входил в разрешённый список (пустой массив
-- проходит всегда).
alter table public.addresses
  drop constraint if exists addresses_schedule_types_check;

alter table public.addresses
  add constraint addresses_schedule_types_check
  check (schedule_types <@ array['2/2', '3/3', '5/2', '6/1', '7/0', 'flexible', 'parttime']::text[]);
