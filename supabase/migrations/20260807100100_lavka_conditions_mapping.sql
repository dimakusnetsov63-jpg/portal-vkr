-- «Условия работы» из выгрузки «Яндекс Лавки» в карточку адреса.
--
-- Выгрузка тикетов несёт не только потребность, но и условия на объекте:
-- станцию метро, график, ночной формат работы и признак разгрузки. Все
-- четыре ложатся на уже существующие поля public.addresses
-- (metro / schedule_type / shift_type / features), но до сих пор
-- отбрасывались — карточки создавались только с required_count.
--
-- Колонки добавляются в column_mapping существующего парсера lavka_v1,
-- новый parser_key не нужен: структура файла не изменилась, парсер просто
-- начал читать те столбцы, которые в нём и так были. `version` поднимается
-- до 2, чтобы в истории импортов (staffing_demand_imports.parser_version)
-- было видно, каким набором правил разобран конкретный файл.
--
-- jsonb-конкатенация (`||`), а не перезапись целиком: идемпотентно и не
-- затирает ключи, если конфиг правили руками.

update public.project_import_configs
set column_mapping = column_mapping || jsonb_build_object(
      'metro', 'Метро',
      'schedule', 'График',
      'nightShift', 'Ночной формат работы',
      'unloading', 'Разгрузка'
    ),
    version = 2
where parser_key = 'lavka_v1';
