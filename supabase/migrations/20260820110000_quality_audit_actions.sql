-- TASK-013, фаза C5 аудита (DATA-03): два новых типа событий в журнале
-- действий портала.
--
-- До этого раздел не писал в `portal_audit_log` ни одной строки. В самой
-- проверке есть снимок «кто/когда создал и изменил», но **что именно**
-- изменилось — не видно. Для раздела, где оценку обсуждают с человеком и
-- иногда оспаривают, это существенный пробел: балл можно поднять после
-- разговора, и следов не останется.
--
-- Это единственная находка аудита, которую нельзя закрыть задним числом:
-- каждый день без журнала — безвозвратно потерянная история правок.
--
-- Отдельной миграцией, как 20260813100000 и все прочие правки enum:
-- Postgres не позволяет использовать новое значение в транзакции, которая
-- его создала, а `supabase db push` выполняет каждый файл в транзакции.

alter type public.portal_audit_action add value if not exists 'quality_review_created';
alter type public.portal_audit_action add value if not exists 'quality_review_updated';
