-- TASK-013, фаза B3 аудита (BUG-05): защита от одновременного
-- редактирования проверки.
--
-- Что было. Двое проверяющих могли открыть одну проверку и сохранить по
-- очереди — второй молча затирал правки первого. Никакой ошибки, никакого
-- следа: просто часть работы исчезала. Раздел вообще-то к этому склонен,
-- потому что RPC переписывает ответы целиком (delete + insert), то есть
-- «последний выигрывает» касается не отдельного поля, а всей проверки.
--
-- Механизм в проекте уже есть — оптимистическая блокировка у вакансий
-- (`portal_save_vacancy_project_tree`, миграция 20260805100600). Переносим
-- дословно, включая текст исключения `version_conflict`: клиент отличает
-- конфликт от прочих ошибок по нему, и заводить второй способ было бы
-- странно.
--
-- Здесь только колонка; проверка версии — в следующей миграции, вместе с
-- пересозданием функции (у неё меняется сигнатура).

alter table public.quality_reviews
  add column version integer not null default 1;

comment on column public.quality_reviews.version is
  'Оптимистическая блокировка: клиент читает версию, открывая проверку, и возвращает её при сохранении. Несовпадение означает, что кто-то сохранил раньше, и правка отвергается вместо тихой перезаписи. Растёт при каждом сохранении через portal_save_quality_review.';
