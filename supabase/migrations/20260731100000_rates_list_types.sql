-- Два новых справочника подсказок для раздела «Ставки»: проекты и юр. лица.
--
-- Отдельной миграцией намеренно: Postgres не позволяет ИСПОЛЬЗОВАТЬ только
-- что добавленное значение enum в той же транзакции, а `supabase db push`
-- выполняет каждый файл миграции в транзакции. Seed-строки, которые эти
-- значения используют, лежат в следующей миграции — тот же приём, что в
-- 20260725100000_add_position_list_type.sql.
--
-- Почему `project` живёт здесь, а не в enum public.candidate_project:
-- в «Ставках» проект = клиент, у которого свой тариф, и этот список бизнес
-- расширяет сам (в исходной таблице ставок клиентов больше 30, в enum — 12).
-- ТЗ раздела прямо требует расширения без изменения схемы, а enum этого не
-- позволяет: `alter type ... add value` — это миграция. Enum
-- candidate_project при этом не трогаем: он остаётся жёстким списком для
-- «Кандидатов»/«Потребности»/«Адресов», и менять его поведение вне задачи
-- «Ставки» нельзя. Сведение двух списков проектов в один — отдельное
-- решение, оно зафиксировано как известное ограничение в
-- docs/requirements/rates.md.

alter type public.candidate_list_type add value if not exists 'project';
alter type public.candidate_list_type add value if not exists 'legal_entity';
