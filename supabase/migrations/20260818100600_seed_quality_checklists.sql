-- TASK-013: засев шаблонов раздела «Контроль качества».
--
-- Девять шаблонов, перенесённых один в один из рабочих файлов:
--   * «Проверка самоотказа» — 4 критерия из «Самоотказы КЦ.xlsx»
--     (листы «База Май/Июнь/Июль/Август», колонки «Возражение отработано»,
--     «…качественно», «Инф-сть комментария», «Причина соответствует»);
--   * восемь чек-листов звонка — по листу на проект из
--     «Чек-листы по проектам.xlsx» (Газпром, Бургер Кинг, Яндекс Лавка,
--     Самокат вахта, Криспи, Самокат местный, МД, Купер).
--
-- Тексты пунктов, порядок блоков и шкалы взяты из файлов программно
-- (разбор выпадающих списков валидации: «1,2,0» → 0-1-2, «2,0» → 0-2,
-- «Да,Нет» → yes_no), а не перепечатаны руками.
--
-- Блок «Возражения» у всех восьми чек-листов заведён с
-- counts_in_total = false: в исходных файлах итог считается как AVERAGE по
-- остальным блокам, о чём написано прямо в заголовке колонки «Общий
-- процент (возражения считаем в отдельной сводной)».
--
-- Что при переносе пришлось поправить — по одному случаю на файл, оба
-- отмечены комментарием на месте:
--   * «Бургер Кинг», пункт «Настойчивость в доведении до приглашения»:
--     список валидации разрешал только 0 и 2, но в данных встречается 1 —
--     Excel не мешает вставить значение мимо списка. Шкала расширена до
--     0-1-2, иначе перенесённая история не прошла бы CHECK;
--   * «Купер», пункт про наличие смартфона на Android: в шапке листа у
--     него пустая ячейка блока, то есть сегодня он не входит ни в один
--     процент вообще. Отнесён к предыдущему блоку — «Заполнение анкеты и
--     проверка документов».
--
-- Проекты названы так же, как в общем справочнике
-- candidate_list_options (list_type = project): «Бургер кинг», «Яндекс
-- лавка», «Самокат местные» — то есть как в файле «Самоотказы КЦ», а не
-- как в заголовках листов чек-листов («Бургер Кинг», «Самокат местный»).
-- Это не косметика: по этому полю шаблон подбирается к проверке.

-- Триггеры версии на время засева отключаются. Иначе каждая из ~300 вставок
-- пунктов и блоков подняла бы version своего шаблона, и свежесозданные
-- шаблоны получили бы номера вида 46 — «версия 46 у того, что никто не
-- правил» приходится потом объяснять вслух. Отключение действует только
-- внутри транзакции этой миграции.
alter table public.quality_checklist_groups disable trigger trg_quality_checklist_groups_bump_version;
alter table public.quality_checklist_items disable trigger trg_quality_checklist_items_bump_version;

-- Проверка самоотказа — общий шаблон (project is null): один на весь
-- портал, применяется к любому проекту.
--
-- Каждый критерий — отдельный блок из одного пункта, а не четыре пункта в
-- одном блоке. Это не формальность: процент блока из одного пункта равен
-- value / 2 × 100, то есть ровно 0% / 50% / 100% — той самой формуле
-- IF(x=0;0%;IF(x=1;50%;IF(x=2;100%))), которая стоит в исходном файле. При
-- «одном блоке на четыре пункта» получилось бы одно усреднённое число, а
-- четыре отдельные метрики — как раз то, по чему строится вся текущая
-- отчётность («% Возражение отработано», «% …качественно», «% Инф-сть
-- комментария», «% Причина соответствует»).
--
-- Итог проверки самоотказа — среднее этих четырёх процентов. В Excel такой
-- цифры нет вовсе; она появляется здесь как побочный результат общей
-- формулы и ничего не ломает: отчётность по-прежнему может смотреть на
-- каждый критерий отдельно, они лежат в group_scores по id блока.
with checklist as (
  insert into public.quality_checklists (title, kind, project)
  values ('Проверка самоотказа', 'refusal', null)
  returning id
), groups as (
  insert into public.quality_checklist_groups (checklist_id, title, sort_order, counts_in_total)
  select checklist.id, v.title, v.sort_order, true
  from checklist, (values
    ('Возражение отработано'::text, 1),
    ('Возражение отработано качественно', 2),
    ('Информативность комментария', 3),
    ('Причина соответствует', 4)
  ) as v(title, sort_order)
  returning id, title
)
insert into public.quality_checklist_items (group_id, title, scale, sort_order)
select groups.id, v.title, v.scale, v.sort_order
from groups
join (values
    ('Возражение отработано'::text, 'Возражение отработано'::text, '0-1-2'::text, 1),
    ('Возражение отработано качественно', 'Возражение отработано качественно', '0-1-2', 2),
    ('Информативность комментария', 'Информативность комментария', '0-1-2', 3),
    ('Причина соответствует', 'Причина соответствует', '0-1-2', 4)
) as v(group_title, title, scale, sort_order) on v.group_title = groups.title;

