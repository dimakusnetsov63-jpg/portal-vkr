-- Два значения enum для журнала: изменение матрицы прав и изменение
-- проектов пользователя (фаза D, ADR-005).
--
-- Отдельной миграцией и раньше той, что их использует: Postgres не
-- позволяет применить новое значение enum в транзакции, которая его
-- создала, а каждый файл миграции выполняется как одна транзакция. В
-- проекте на это уже дважды напарывались — 20260725100000/20260725100100
-- и 20260805100700/20260805100800 разбиты по той же причине (см.
-- docs/database/migrations.md, раздел «Порядок применения»).
--
-- Значения именуются как существующие: подлежащее_сказуемое в прошедшем
-- времени (user_created, user_role_changed, ...).

alter type public.portal_audit_action add value 'section_permission_changed';
alter type public.portal_audit_action add value 'user_projects_changed';
