-- TASK-013, исправление засева: у чек-листа «Самокат местные» вместо
-- текстов пунктов оказались продублированы названия блоков.
--
-- Откуда взялось. Засев 20260818100600 сгенерирован из файла «Чек-листы по
-- проектам.xlsx» программно: строка 1 листа — блок, строка 2 — пункт. На
-- листе «Самокат местный» шапка устроена иначе: во второй строке там снова
-- названия блоков, а тексты вопросов живут в объединённых ячейках. Генератор
-- этого не заметил и записал 35 пунктов вида «Сбор первичной информации».
-- Остальные восемь шаблонов проверены запросом `i.title = g.title` — там
-- ноль совпадений, дефект изолирован этим листом.
--
-- (У шаблона самоотказа такое совпадение штатно: каждый критерий — блок из
-- одного пункта, и названия совпадают по построению.)
--
-- Тексты ниже — от бизнеса напрямую (скрипт «Самокат», 19 августа 2026), а
-- не повторный разбор того же листа: разбирать нечего, в файле их нет в
-- машиночитаемом виде.
--
-- Структура не меняется: те же 9 блоков и те же 35 пунктов в том же
-- порядке, меняются только заголовки. Поэтому шкалы, веса и порядок не
-- трогаются — они прочитаны из списков валидации соответствующих колонок и
-- верны (сбой был только в чтении строки заголовка, не колонок).
--
-- Заполненные проверки по этому шаблону на момент миграции отсутствуют
-- (`select count(*) from quality_reviews r join quality_checklists c on
-- c.id = r.checklist_id where c.project = 'Самокат местные'` → 0), так что
-- переименование ничью оценку не переписывает.

-- Триггер версии на время правки отключается: 35 UPDATE'ов подняли бы
-- version до 36, хотя логическая правка одна. Версия выставляется вручную
-- ниже — она должна вырасти, чтобы «шаблон менялся» было видно.
