-- Общие справочники читает любой сотрудник портала, а не только аудитория
-- раздела «Кандидаты».
--
-- ЧТО СЛОМАЛОСЬ. Роль «ОКК» заведена без прав, разделы ей назначает
-- руководитель, и на практике ей выдан один раздел — «Контроль качества».
-- В форме проверки при этом пусты **все** выпадающие списки сразу: проект,
-- сотрудник, возражение, нарушение. Выбрать проект нельзя вовсе, а форма
-- сообщает «Для проекта „—" нет шаблона», хотя шаблоны заведены.
--
-- ПОЧЕМУ. Политика чтения candidate_list_options требовала
-- portal_can_view_section('candidates'):
--
--   using (public.portal_can_view_section('candidates'))
--
-- У ОКК раздела «Кандидаты» нет, поэтому select возвращал ноль строк. Не
-- ошибку — именно ноль строк, поэтому интерфейс не мог отличить «нет
-- доступа» от «справочник пуст» и честно рисовал пустой список.
--
-- Политика написана 11 августа (20260811110100) и на тот момент была
-- верной: таблица называется candidate_list_options и была справочником
-- кандидатов. Но 31 июля TASK-009 сделал её **общепортальной** — теперь в
-- ней живут проекты, города, должности, юрлица, категории вакансий,
-- причины увольнения и возврата, а с 18 августа ещё возражения и нарушения
-- контроля качества. Читают её шесть разделов: «Кандидаты»,
-- «Потребность», «Адреса», «Ставки», «Описание вакансии» и «Контроль
-- качества». Условие доступа осталось от прежнего, узкого смысла таблицы.
--
-- ПОЧЕМУ НЕ ТОЧЕЧНО. Соблазн дописать `or portal_can_view_section('quality')`
-- нужно отвергнуть: это чинит один случай из шести и оставляет ту же
-- ловушку. Роль, которой выдали только «Ставки» или только «Адреса»,
-- упрётся в ровно ту же пустоту, и найдётся это снова через жалобу
-- пользователя, а не через тест.
--
-- ЧТО ЭТО ОТКРЫВАЕТ. Названия проектов, городов, должностей, юрлиц,
-- категорий вакансий, формулировки причин и возражений, а также имена
-- сотрудников из списков «Рекрутеры»/«Менеджеры»/«Координаторы». Ни одного
-- поля кандидата: персональные данные лежат в candidates, и её политики
-- эта миграция не трогает. Для внутреннего портала, где каждый
-- пользователь — сотрудник, это подсказки ввода, а не тайна.
--
-- Оговорка, которую важно назвать вслух: проектная изоляция H-6 к этой
-- таблице не применяется и не применялась. Сотрудник, ограниченный одним
-- проектом, видит названия всех проектов в справочнике. Это свойство
-- существовало и до миграции — для всех, у кого есть «Кандидаты»;
-- миграция расширяет круг читателей, но не состав видимого.
--
-- ЗАПИСЬ НЕ МЕНЯЕТСЯ. insert/update по-прежнему требуют
-- portal_can_edit_section('settings'), то есть править справочники может
-- только руководитель и координатор. Delete-политики у таблицы нет с
-- 20260722214949 (мягкое удаление через is_active) — здесь она намеренно
-- не появляется.
--
-- Откат: вернуть прежнее определение из 20260811110100.

-- Именованный предикат вместо повторения exists-подзапроса: условие
-- «просто сотрудник портала» будет нужно и другим справочникам, а
-- безымянное условие в политике никто не найдёт поиском.
create or replace function public.portal_is_active_user()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.portal_users u
    where u.id = public.portal_current_user_id()
      and u.is_active
  );
$$;

comment on function public.portal_is_active_user() is
  'Есть ли активная учётная запись портала у текущего запроса. Для данных, доступных любому сотруднику независимо от набора разделов, — сегодня это общие справочники candidate_list_options. Не заменяет portal_can_view_section: та отвечает на вопрос о разделе, эта — о самом факте входа.';

revoke execute on function public.portal_is_active_user() from public;
grant execute on function public.portal_is_active_user() to anon, authenticated;

drop policy "portal_select_candidate_list_options" on public.candidate_list_options;

create policy "portal_select_candidate_list_options"
  on public.candidate_list_options for select to authenticated
  using (public.portal_is_active_user());

comment on table public.candidate_list_options is
  'Общепортальные справочники подсказок: проекты, города, должности, юрлица, категории вакансий, причины увольнения и возврата, возражения и нарушения контроля качества, а также имена рекрутеров/менеджеров/координаторов. Название таблицы историческое — с TASK-009 (31 июля 2026) справочник не только кандидатский, его читают шесть разделов. Читает любой активный сотрудник портала, правит только тот, кому доступно редактирование «Настроек».';
