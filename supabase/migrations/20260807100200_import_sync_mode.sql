-- Режим импорта «Синхронизировать» и счётчик обнулённых объектов.
--
-- Проблема, которую он решает: выгрузка тикетов показывает только открытые
-- позиции. Когда объект закрыли (все тикеты по нему ушли в «Закрыт»), он
-- просто исчезает из файла — и карточка адреса навсегда сохраняет старое
-- «Требуется: 10». Режимы «Заменить»/«Добавить» трогают только те объекты,
-- которые в файле есть, поэтому данные тихо устаревают.
--
-- «Синхронизировать» = «Заменить» + обнулить required_count у карточек
-- проекта, которых в файле нет. Обнуление, а не архивирование и не
-- удаление: объект физически существует и, скорее всего, снова появится в
-- следующей выгрузке — вместе со всем, что координатор заполнил руками
-- (метро, график, контакты).
--
-- Обнуляются только карточки с source = 'excel'. Заведённые вручную не
-- трогаются: файл не является для них источником истины, и молча обнулять
-- чужую работу нельзя.

-- `if exists` / `if not exists` — миграции применяются руками через SQL
-- Editor, без раннера, отслеживающего «применено/нет»: повторный запуск
-- должен быть безопасен, а не падать на середине.
alter table public.staffing_demand_imports
  drop constraint if exists staffing_demand_imports_mode_check;

alter table public.staffing_demand_imports
  add constraint staffing_demand_imports_mode_check
  check (mode in ('replace', 'add', 'sync'));

alter table public.staffing_demand_imports
  add column if not exists zeroed_rows integer not null default 0;

comment on column public.staffing_demand_imports.zeroed_rows is
  'Сколько карточек адресов импорт обнулил как отсутствующие в файле (только режим sync). Ноль для остальных режимов.';
