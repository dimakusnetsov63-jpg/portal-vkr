-- TASK-013, раздел «Контроль качества»: два новых типа управляемых
-- справочников для «Настройки → Списки».
--
--   qc_objection — возражение кандидата при самоотказе. 24 значения из
--                  выпадающего списка листов «База …» файла «Самоотказы КЦ»
--                  засеваются отдельной миграцией 20260818100700.
--   qc_violation — нарушение, зафиксированное при проверке звонка (колонка
--                  «Нарушение» в листах файла «Чек-листы по проектам»).
--                  Значениями не засевается: в исходных листах эта колонка
--                  заполнена бессистемно — на «Яндекс Лавке» в ней лежат
--                  числа 0/2, на «Самокате местном» — текст рекомендаций,
--                  то есть готового словаря там нет. Список наполняется
--                  бизнесом через Настройки.
--
-- Проект и должность своими справочниками НЕ обзаводятся: раздел берёт
-- общие списки `project` и `position` (TASK-009) — тот же принцип, что у
-- «Адресов»/«Ставок»/«Кандидатов».
--
-- Отдельной миграцией, как 20260805100700_add_vacancy_category_list_type и
-- 20260725100000_add_position_list_type: Postgres не позволяет использовать
-- только что добавленное значение enum в той же транзакции, а `supabase db
-- push` выполняет каждый файл миграции в транзакции. Строки, которые
-- ссылаются на 'qc_objection', живут в следующих миграциях.

alter type public.candidate_list_type add value if not exists 'qc_objection';
alter type public.candidate_list_type add value if not exists 'qc_violation';
