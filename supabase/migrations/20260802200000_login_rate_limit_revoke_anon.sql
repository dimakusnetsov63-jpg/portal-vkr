-- Фаза 3 из трёх (C-3/C-4) — закрытие прямого анонимного доступа к
-- auth-RPC. Точка невозврата: после применения приложение, ещё не
-- перешедшее на доверенную роль `portal_auth_caller` (код фазы 2),
-- потеряет возможность входить и проверять сессии.
--
-- Применять только после подтверждённой фазы 2 в production. Порядок и
-- обоснование — docs/ROLLOUT-login-rate-limit.md, раздел 3.
--
-- Верификация фазы 2 в production на момент написания этой миграции:
--   * ограничение частоты срабатывает и растёт экспоненциально
--     (наблюдалось: retry_after 2 -> 4 -> 16 секунд на последовательных
--     сериях неудачных попыток);
--   * лимит привязан к ИСТОЧНИКУ (ip_hash), а не к логину — запрос другим,
--     ранее не встречавшимся логином с уже ограниченного IP немедленно
--     получил тот же 429, что подтверждает: в WHERE-условии участвует
--     только ip_hash, отдельного счётчика на логин нет;
--   * другой физический источник (учётная запись администратора,
--     собственная сеть) не пострадал от нагрузки на первый IP — во время
--     входа сообщения об ограничении не было;
--   * сброс счётчика при успешном входе воспроизведён явно: три неудачные
--     попытки -> успешный вход -> следующая неудачная попытка вернула
--     обычную «Неверный логин или пароль» (401), а не «Слишком много
--     попыток» (429) — то есть успешный вход действительно очищает
--     накопленные неудачи по паре (источник, учётная запись), а не только
--     не даёт им расти;
--   * IP из x-forwarded-for реально доходит до базы — заключение косвенное,
--     но исчерпывающее: если бы `p_ip` приходил NULL, ограничение по
--     источнику не сработало бы вовсе (см. ветку `if v_ip_hash is not null`
--     в portal_login), а оно сработало и росло предсказуемо.
--
-- Что именно закрывается этой миграцией
-- --------------------------------------
-- Пока анонимный доступ к RPC остаётся, ограничение по IP декоративно для
-- любого, кто обращается к PostgREST напрямую, минуя портал: такой вызов
-- может передать p_ip = NULL (тогда ограничение не применяется вовсе) или
-- любое произвольное значение (тогда лимит считается по фиктивному
-- источнику и не мешает переборщику). Только приложение через
-- /api/auth/login подставляет реальный IP из заголовка запроса — доверять
-- этому значению можно лишь тогда, когда путь к RPC гарантированно идёт
-- через приложение, а не в обход него.
--
-- Задел на будущее: развёрнутое приложение уже не использует анонимный
-- путь вовсе — authDb() в lib/auth/session.ts всегда подписывает токен
-- под ролью portal_auth_caller (см. lib/auth/jwt.ts,
-- signPortalServiceJwt). Поэтому применение этой миграции ничего не
-- меняет для текущей работающей версии портала — она лишь закрывает
-- путь для прямых вызовов мимо приложения.

revoke execute on function public.portal_login(text, text, text, text) from anon;
revoke execute on function public.portal_session_context(text) from anon;
revoke execute on function public.portal_logout(text) from anon;
