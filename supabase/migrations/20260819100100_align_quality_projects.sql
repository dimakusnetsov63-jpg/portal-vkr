-- TASK-013: названия проектов в шаблонах приводятся к общему справочнику
-- портала (`candidate_list_options`, `list_type = project`).
--
-- Что было не так. Засев 20260818100600 взял названия проектов из
-- выпадающего списка рабочего файла «Самоотказы КЦ» («Бургер кинг»,
-- «Яндекс лавка», «Самокат местные», «МД», «Газпром»). В портале же с
-- TASK-009 действует один справочник проектов на все разделы, и там эти же
-- клиенты названы иначе: «Бургер кинг Россия», «Яндекс Лавка», «Самокат»,
-- «Мастер Деливери», «Газпромнефть».
--
-- Последствие было не косметическим: шаблон подбирается по точному
-- совпадению `quality_checklists.project` с выбранным в форме проектом, а
-- форма предлагает значения справочника. То есть ни один чек-лист звонка
-- не находился вовсе — раздел молча предлагал завести шаблон. Проверки
-- самоотказов при этом работали: у них общий шаблон с `project is null`.
--
-- Решение по «Самокату» принято бизнесом 19 августа 2026: скрипты по
-- должностям (курьеры / операторы кухни) и по типу занятости (местные /
-- вахта) **не разделяем** — логика проектов остаётся такой же, как в
-- остальных разделах портала, один шаблон на проект. Поэтому «Самокат
-- местные» становится шаблоном проекта «Самокат» (его пункты выверены с
-- бизнесом миграцией 20260819100000), а «Самокат вахта» архивируется.
--
-- Архивируется, а не удаляется: 37 пунктов вахтового варианта отличаются
-- формулировками, и если решение однажды пересмотрят, восстановление — это
-- `archived_at = null`, а не повторный разбор Excel.
--
-- «Криспи» намеренно НЕ переименован: в справочнике портала такого проекта
-- нет вовсе, а похожий по звучанию «Кранчи Дрим» — это утверждение о
-- бизнесе, которое я делать не вправе. Шаблон остаётся с прежним
-- названием и не подберётся ни к одному проекту, пока бизнес не скажет,
-- заводить ли «Криспи» в справочник или это существующий клиент под другим
-- именем. Такое состояние честнее, чем угаданная привязка.

-- Порядок важен: сначала архивируем вахтовый шаблон, иначе после
-- переименования обоих на «Самокат» частичный уникальный индекс
-- quality_checklists_kind_project_key (он считает только строки с
-- archived_at is null) отвергнет второй.
update public.quality_checklists
set archived_at = now()
where kind = 'call' and project = 'Самокат вахта';

update public.quality_checklists
set project = case project
  when 'Газпром'          then 'Газпромнефть'
  when 'Бургер кинг'      then 'Бургер кинг Россия'
  when 'Яндекс лавка'     then 'Яндекс Лавка'
  when 'МД'               then 'Мастер Деливери'
  when 'Самокат местные'  then 'Самокат'
  when 'Самокат вахта'    then 'Самокат'
  else project
end
where kind = 'call'
  and project in ('Газпром', 'Бургер кинг', 'Яндекс лавка', 'МД', 'Самокат местные', 'Самокат вахта');

-- Заголовки шаблонов приводятся в соответствие с новыми названиями:
-- «Чек-лист звонка — Бургер кинг» при проекте «Бургер кинг Россия» читался
-- бы как другой шаблон.
update public.quality_checklists
set title = 'Чек-лист звонка — ' || project
where kind = 'call' and archived_at is null;

update public.quality_checklists
set title = 'Чек-лист звонка — Самокат (вахта, архив)'
where kind = 'call' and archived_at is not null and project = 'Самокат';
