-- Признак «доступны все проекты» у учётной записи (фаза A).
--
-- Аддитивная миграция. Колонка добавляется со значением false для всех
-- существующих строк, а portal_has_project() начинает её учитывать только
-- в следующей миграции (20260811100200) — до тех пор поле ни на что не
-- влияет. Наблюдаемое поведение не меняется ни для одной роли.
--
-- Зачем: сегодня «видит все проекты» умеет только роль head — это зашито
-- в portal_has_project(). Для остальных ролей единственный способ выдать
-- доступ ко всем проектам — перечислить их руками в portal_users.projects
-- и не забывать дописывать туда каждый новый проект. Чекбокс «Все
-- проекты» из ТЗ (раздел «Настройки пользователя») без отдельного признака
-- нереализуем: массив не отличает «выбраны все двенадцать» от «выбраны
-- любые, какие появятся».
--
-- head сознательно НЕ переводится на этот признак: его bypass остаётся
-- там же, где был (в самой функции), и не зависит от того, что
-- администратор выставил в карточке. Иначе руководителя можно было бы
-- случайно отрезать от данных, сняв галочку.

alter table public.portal_users
  add column all_projects boolean not null default false;

comment on column public.portal_users.all_projects is
  'true — сотрудник видит все проекты, включая те, что появятся позже (projects при этом игнорируется). false — только перечисленные в projects. К роли head отношения не имеет: у неё доступ ко всем проектам зашит в portal_has_project() и не выключается.';

-- Заодно снимается устаревшее описание соседней колонки: с H-6 (миграции
-- 20260803130000/20260803140000) projects перестала быть информационной —
-- по ней фильтруют политики RLS семи таблиц.
comment on column public.portal_users.projects is
  'Проекты сотрудника — значения справочника candidate_list_options (list_type = project) как текст, без FK (список проектов расширяется независимо). Используется в RLS через portal_has_project(): роль видит только строки своих проектов. Игнорируется, если all_projects = true или роль head.';
